// Command websymbols writes src/web/symbols.data.ts, the tables the
// browser build's Symbols (src/web/symbols.ts) draws from: the desktop's
// stand-ins, Phosphor weights and SF metrics, read from the Go sources that
// declare them, and each Phosphor file's path with the bounds of its ink.
//
//	go run ./cmd/websymbols          regenerate
//	go run ./cmd/websymbols -check   exit 1 when the committed file is stale
package main

import (
	"bytes"
	"cmp"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"math"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// Out is the generated file, from the repository root.
const Out = "src/web/symbols.data.ts"

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "verify "+Out+" is current instead of writing it")
	flag.Parse()
	want, err := generate(*root)
	if err != nil {
		fail(err)
	}
	path := filepath.Join(*root, Out)
	if *check {
		got, err := os.ReadFile(path)
		if err != nil {
			fail(err)
		}
		if !bytes.Equal(got, want) {
			fail(fmt.Errorf("%s is stale; run go run ./cmd/websymbols", Out))
		}
		fmt.Println("web symbols: ok")
		return
	}
	if err := os.WriteFile(path, want, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "websymbols:", err)
	os.Exit(1)
}

type standIn struct {
	Symbol string `json:"symbol"`
	Icon   string `json:"icon"`
	Solid  bool   `json:"solid"`
}

type sfMetric struct {
	Symbol  string       `json:"symbol"`
	Weights [][7]float64 `json:"weights"`
}

type pathInk struct {
	D   string     `json:"d"`
	Ink [4]float64 `json:"ink"`
}

// generate reads symbols.go, symbols_other.go, symbols_sfmetrics.go and
// third_party/phosphor under root and returns the TS module.
func generate(root string) ([]byte, error) {
	lits, err := parseVars(root, "symbols.go", "symbols_other.go", "symbols_sfmetrics.go")
	if err != nil {
		return nil, err
	}
	var weights, phosphorWeights []string
	var standIns []standIn
	var metrics []sfMetric
	for _, v := range []struct {
		name string
		read func(*ast.CompositeLit) error
	}{
		{"symbolWeights", func(l *ast.CompositeLit) (err error) { weights, err = strs(l); return }},
		{"phosphorWeights", func(l *ast.CompositeLit) (err error) { phosphorWeights, err = strs(l); return }},
		{"standIns", func(l *ast.CompositeLit) (err error) { standIns, err = readStandIns(l); return }},
		{"sfMetrics", func(l *ast.CompositeLit) (err error) { metrics, err = readMetrics(l); return }},
	} {
		l := lits[v.name]
		if l == nil {
			return nil, fmt.Errorf("no var %s", v.name)
		}
		if err := v.read(l); err != nil {
			return nil, fmt.Errorf("%s: %w", v.name, err)
		}
	}
	if len(phosphorWeights) != len(weights) {
		return nil, fmt.Errorf("%d Phosphor weights for %d SF weights", len(phosphorWeights), len(weights))
	}
	for _, m := range metrics {
		if len(m.Weights) != len(weights) {
			return nil, fmt.Errorf("sfMetrics %s: %d boxes for %d weights", m.Symbol, len(m.Weights), len(weights))
		}
	}

	// Every file a stand-in draws (symbols_other.go:33-41, file).
	paths := map[string]pathInk{}
	for _, s := range standIns {
		for w := range weights {
			file := phosphorFile(s, phosphorWeights[w])
			if _, ok := paths[file]; ok {
				continue
			}
			src, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(file)))
			if err != nil {
				return nil, err
			}
			d, err := svgPath(string(src))
			if err != nil {
				return nil, fmt.Errorf("%s: %w", file, err)
			}
			ink, err := pathBounds(d)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", file, err)
			}
			paths[file] = pathInk{d, ink}
		}
	}

	var b bytes.Buffer
	b.WriteString(`// Code generated by go run ./cmd/websymbols; DO NOT EDIT.
// symbolWeights and standIns from symbols.go, phosphorWeights from symbols_other.go, sfMetrics from
// symbols_sfmetrics.go, and phosphor: each drawn file's path in third_party/phosphor
// (@phosphor-icons/core 2.1.1, MIT, third_party/phosphor/LICENSE) with its ink's bounds [minX, minY,
// maxX, maxY] by symbols_other.go pathBounds.

`)
	var jerr error
	line := func(format string, v any) {
		j, err := marshal(v)
		jerr = cmp.Or(jerr, err)
		fmt.Fprintf(&b, format, j)
	}
	line("export const symbolWeights: readonly string[] = %s;\n", weights)
	line("export const phosphorWeights: readonly string[] = %s;\n", phosphorWeights)
	b.WriteString("export const standIns: readonly { symbol: string; icon: string; solid: boolean }[] = [\n")
	for _, s := range standIns {
		line(" %s,\n", s)
	}
	b.WriteString("];\n// Per weight: width, height, baseline, left, top, right, bottom.\n")
	b.WriteString("export const sfMetrics: readonly { symbol: string; weights: readonly (readonly [number, number, number, number, number, number, number])[] }[] = [\n")
	for _, m := range metrics {
		line(" %s,\n", m)
	}
	b.WriteString("];\nexport const phosphor: Readonly<Record<string, { d: string; ink: readonly [number, number, number, number] }>> = {\n")
	files := make([]string, 0, len(paths))
	for f := range paths {
		files = append(files, f)
	}
	slices.Sort(files)
	for _, f := range files {
		line(" %s: ", f)
		line("%s,\n", paths[f])
	}
	b.WriteString("};\n")
	return b.Bytes(), jerr
}

func marshal(v any) ([]byte, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return bytes.TrimSuffix(b.Bytes(), []byte("\n")), nil
}

// phosphorFile is standIn.file (symbols_other.go:33-41) for Phosphor weight pw.
func phosphorFile(s standIn, pw string) string {
	if s.Solid {
		return "third_party/phosphor/fill/" + s.Icon + "-fill.svg"
	}
	if pw != "regular" {
		return "third_party/phosphor/" + pw + "/" + s.Icon + "-" + pw + ".svg"
	}
	return "third_party/phosphor/regular/" + s.Icon + ".svg"
}

// parseVars returns the composite literal each package-level var in files
// is set to.
func parseVars(root string, files ...string) (map[string]*ast.CompositeLit, error) {
	lits := map[string]*ast.CompositeLit{}
	fset := token.NewFileSet()
	for _, name := range files {
		f, err := parser.ParseFile(fset, filepath.Join(root, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		for _, decl := range f.Decls {
			g, ok := decl.(*ast.GenDecl)
			if !ok || g.Tok != token.VAR {
				continue
			}
			for _, spec := range g.Specs {
				v := spec.(*ast.ValueSpec)
				for i, n := range v.Names {
					if i < len(v.Values) {
						if l, ok := v.Values[i].(*ast.CompositeLit); ok {
							lits[n.Name] = l
						}
					}
				}
			}
		}
	}
	return lits, nil
}

func strs(l *ast.CompositeLit) ([]string, error) {
	out := make([]string, len(l.Elts))
	for i, e := range l.Elts {
		s, err := str(e)
		if err != nil {
			return nil, err
		}
		out[i] = s
	}
	return out, nil
}

func str(e ast.Expr) (string, error) {
	if b, ok := e.(*ast.BasicLit); ok && b.Kind == token.STRING {
		return strconv.Unquote(b.Value)
	}
	return "", fmt.Errorf("want a string literal, have %T", e)
}

func float(e ast.Expr) (float64, error) {
	neg := false
	if u, ok := e.(*ast.UnaryExpr); ok && (u.Op == token.SUB || u.Op == token.ADD) {
		neg, e = u.Op == token.SUB, u.X
	}
	b, ok := e.(*ast.BasicLit)
	if !ok || (b.Kind != token.FLOAT && b.Kind != token.INT) {
		return 0, fmt.Errorf("want a number literal, have %T", e)
	}
	v, err := strconv.ParseFloat(b.Value, 64)
	if neg {
		v = -v
	}
	return v, err
}

func elts(e ast.Expr, n int) ([]ast.Expr, error) {
	l, ok := e.(*ast.CompositeLit)
	if !ok || (n >= 0 && len(l.Elts) != n) {
		return nil, fmt.Errorf("want a composite literal of %d elements", n)
	}
	return l.Elts, nil
}

func readStandIns(l *ast.CompositeLit) ([]standIn, error) {
	var out []standIn
	for _, e := range l.Elts {
		f, err := elts(e, 3)
		if err != nil {
			return nil, err
		}
		symbol, err := str(f[0])
		if err != nil {
			return nil, err
		}
		icon, err := str(f[1])
		if err != nil {
			return nil, err
		}
		solid, ok := f[2].(*ast.Ident)
		if !ok || (solid.Name != "true" && solid.Name != "false") {
			return nil, fmt.Errorf("%s: want true or false", symbol)
		}
		out = append(out, standIn{symbol, icon, solid.Name == "true"})
	}
	return out, nil
}

func readMetrics(l *ast.CompositeLit) ([]sfMetric, error) {
	var out []sfMetric
	for _, e := range l.Elts {
		f, err := elts(e, 2)
		if err != nil {
			return nil, err
		}
		symbol, err := str(f[0])
		if err != nil {
			return nil, err
		}
		boxes, err := elts(f[1], -1)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", symbol, err)
		}
		m := sfMetric{Symbol: symbol}
		for _, box := range boxes {
			vs, err := elts(box, 7)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", symbol, err)
			}
			var w [7]float64
			for i, v := range vs {
				if w[i], err = float(v); err != nil {
					return nil, fmt.Errorf("%s: %w", symbol, err)
				}
			}
			m.Weights = append(m.Weights, w)
		}
		out = append(out, m)
	}
	return out, nil
}

// svgPath, pathBounds, arcPoints and pathScanner are symbols_other.go's
// (98-325), which package main of the repository root keeps to itself:
// TestWebSymbolsGolden there holds src/web/symbols.ts, drawing from this
// output, to the desktop's own drawing.

// svgPath returns the d attribute of the one path in a Phosphor SVG.
func svgPath(svg string) (string, error) {
	_, rest, ok := strings.Cut(svg, "<path")
	if !ok || strings.Contains(rest, "<path") {
		return "", errors.New("want exactly one path")
	}
	_, d, ok := strings.Cut(rest, ` d="`)
	if !ok {
		return "", errors.New("path has no d")
	}
	d, _, ok = strings.Cut(d, `"`)
	if !ok {
		return "", errors.New("path's d is not closed")
	}
	return d, nil
}

// pathBounds returns the bounds [minX, minY, maxX, maxY] of the outline
// an SVG path draws. Curves and arcs are measured at 64 points each, which
// is within 0.05 units for Phosphor's 256-unit icons.
func pathBounds(d string) ([4]float64, error) {
	b := [4]float64{math.Inf(1), math.Inf(1), math.Inf(-1), math.Inf(-1)}
	add := func(x, y float64) {
		b[0], b[1] = math.Min(b[0], x), math.Min(b[1], y)
		b[2], b[3] = math.Max(b[2], x), math.Max(b[3], y)
	}
	const steps = 64
	p := pathScanner{s: d}
	var (
		cmd                 byte
		x, y, sx, sy        float64
		cx, cy              float64 // last control point, for S and T
		prevCubic, prevQuad bool
	)
	for {
		c, ok := p.command()
		if !ok {
			break
		}
		if c != 0 {
			cmd = c
		} else if cmd == 0 || cmd == 'Z' || cmd == 'z' {
			return b, fmt.Errorf("number without a command at %d", p.i)
		}
		rel := cmd >= 'a'
		ox, oy := 0.0, 0.0
		if rel {
			ox, oy = x, y
		}
		var nums [7]float64
		// The numbers each command takes, by "MLHVCSQTAZ".
		need := [...]int{2, 2, 1, 1, 6, 4, 4, 2, 7, 0}[strings.IndexByte("MLHVCSQTAZ", cmd&^0x20)]
		for i := range need {
			v, err := p.number(cmd&^0x20 == 'A' && (i == 3 || i == 4))
			if err != nil {
				return b, err
			}
			nums[i] = v
		}
		cubic, quad := false, false
		switch cmd &^ 0x20 {
		case 'M':
			x, y = ox+nums[0], oy+nums[1]
			sx, sy = x, y
			add(x, y)
			// Further pairs after a moveto are linetos.
			if rel {
				cmd = 'l'
			} else {
				cmd = 'L'
			}
		case 'L':
			x, y = ox+nums[0], oy+nums[1]
			add(x, y)
		case 'H':
			x = ox + nums[0]
			add(x, y)
		case 'V':
			y = oy + nums[0]
			add(x, y)
		case 'C', 'S':
			var x1, y1, x2, y2, ex, ey float64
			if cmd&^0x20 == 'C' {
				x1, y1, x2, y2, ex, ey = ox+nums[0], oy+nums[1], ox+nums[2], oy+nums[3], ox+nums[4], oy+nums[5]
			} else {
				x1, y1 = x, y
				if prevCubic {
					x1, y1 = 2*x-cx, 2*y-cy
				}
				x2, y2, ex, ey = ox+nums[0], oy+nums[1], ox+nums[2], oy+nums[3]
			}
			for i := 1; i <= steps; i++ {
				t := float64(i) / steps
				u := 1 - t
				add(u*u*u*x+3*u*u*t*x1+3*u*t*t*x2+t*t*t*ex, u*u*u*y+3*u*u*t*y1+3*u*t*t*y2+t*t*t*ey)
			}
			cx, cy, x, y, cubic = x2, y2, ex, ey, true
		case 'Q', 'T':
			var x1, y1, ex, ey float64
			if cmd&^0x20 == 'Q' {
				x1, y1, ex, ey = ox+nums[0], oy+nums[1], ox+nums[2], oy+nums[3]
			} else {
				x1, y1 = x, y
				if prevQuad {
					x1, y1 = 2*x-cx, 2*y-cy
				}
				ex, ey = ox+nums[0], oy+nums[1]
			}
			for i := 1; i <= steps; i++ {
				t := float64(i) / steps
				u := 1 - t
				add(u*u*x+2*u*t*x1+t*t*ex, u*u*y+2*u*t*y1+t*t*ey)
			}
			cx, cy, x, y, quad = x1, y1, ex, ey, true
		case 'A':
			ex, ey := ox+nums[5], oy+nums[6]
			arcPoints(x, y, nums[0], nums[1], nums[2], nums[3] != 0, nums[4] != 0, ex, ey, steps, add)
			x, y = ex, ey
		case 'Z':
			x, y = sx, sy
		}
		prevCubic, prevQuad = cubic, quad
	}
	if math.IsInf(b[0], 0) {
		return b, errors.New("empty path")
	}
	return b, nil
}

// arcPoints calls add with points along an SVG elliptical arc from
// (x1, y1) to (x2, y2), converted to its centre as in SVG 1.1 F.6.5.
func arcPoints(x1, y1, rx, ry, angle float64, large, sweep bool, x2, y2 float64, steps int, add func(x, y float64)) {
	rx, ry = math.Abs(rx), math.Abs(ry)
	if rx == 0 || ry == 0 || (x1 == x2 && y1 == y2) {
		add(x2, y2)
		return
	}
	phi := angle * math.Pi / 180
	cos, sin := math.Cos(phi), math.Sin(phi)
	dx, dy := (x1-x2)/2, (y1-y2)/2
	x1p, y1p := cos*dx+sin*dy, -sin*dx+cos*dy
	if l := x1p*x1p/(rx*rx) + y1p*y1p/(ry*ry); l > 1 {
		rx, ry = rx*math.Sqrt(l), ry*math.Sqrt(l)
	}
	num := rx*rx*ry*ry - rx*rx*y1p*y1p - ry*ry*x1p*x1p
	den := rx*rx*y1p*y1p + ry*ry*x1p*x1p
	f := math.Sqrt(math.Max(0, num/den))
	if large == sweep {
		f = -f
	}
	cxp, cyp := f*rx*y1p/ry, -f*ry*x1p/rx
	cx, cy := cos*cxp-sin*cyp+(x1+x2)/2, sin*cxp+cos*cyp+(y1+y2)/2
	theta := math.Atan2((y1p-cyp)/ry, (x1p-cxp)/rx)
	delta := math.Atan2((-y1p-cyp)/ry, (-x1p-cxp)/rx) - theta
	if sweep && delta < 0 {
		delta += 2 * math.Pi
	} else if !sweep && delta > 0 {
		delta -= 2 * math.Pi
	}
	for i := 1; i <= steps; i++ {
		a := theta + delta*float64(i)/float64(steps)
		ex, ey := rx*math.Cos(a), ry*math.Sin(a)
		add(cos*ex-sin*ey+cx, sin*ex+cos*ey+cy)
	}
}

// pathScanner reads the commands and numbers of SVG path data.
type pathScanner struct {
	s string
	i int
}

func (p *pathScanner) skip() {
	for p.i < len(p.s) && (p.s[p.i] == ' ' || p.s[p.i] == ',' || p.s[p.i] == '\t' || p.s[p.i] == '\n' || p.s[p.i] == '\r') {
		p.i++
	}
}

// command returns the next command letter, 0 when a number follows
// instead, and false at the end.
func (p *pathScanner) command() (byte, bool) {
	p.skip()
	if p.i == len(p.s) {
		return 0, false
	}
	if c := p.s[p.i]; strings.IndexByte("MmLlHhVvCcSsQqTtAaZz", c) >= 0 {
		p.i++
		return c, true
	}
	return 0, true
}

// number reads a number, or with flag an arc flag, which may run into
// what follows it ("a8 8 0 018-8").
func (p *pathScanner) number(flag bool) (float64, error) {
	p.skip()
	start := p.i
	if flag {
		if p.i < len(p.s) && (p.s[p.i] == '0' || p.s[p.i] == '1') {
			p.i++
			return float64(p.s[start] - '0'), nil
		}
		return 0, fmt.Errorf("want an arc flag at %d", start)
	}
	if p.i < len(p.s) && (p.s[p.i] == '-' || p.s[p.i] == '+') {
		p.i++
	}
	dot, exp := false, false
scan:
	for ; p.i < len(p.s); p.i++ {
		switch c := p.s[p.i]; {
		case c >= '0' && c <= '9':
		case c == '.' && !dot && !exp:
			dot = true
		case (c == 'e' || c == 'E') && !exp:
			exp = true
			if p.i+1 < len(p.s) && (p.s[p.i+1] == '-' || p.s[p.i+1] == '+') {
				p.i++
			}
		default:
			break scan
		}
	}
	v, err := strconv.ParseFloat(p.s[start:p.i], 64)
	if err != nil {
		return 0, fmt.Errorf("bad number at %d: %q", start, p.s[start:p.i])
	}
	return v, nil
}
